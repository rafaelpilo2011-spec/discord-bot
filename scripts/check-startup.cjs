const assert = require('node:assert/strict');
process.env.DISCORD_TOKEN = 'test-placeholder';
process.env.CLIENT_ID = '123456789012345678';
process.env.GUILD_ID = '234567890123456789';
process.env.DATABASE_URL = 'postgresql://test:test@127.0.0.1:1/test';
const { REST } = require('@discordjs/rest');
let registered;
REST.prototype.put = async (_, options) => { registered = options.body; };
const { DiscordBot } = require('../dist/index');
const event = require('../dist/events/interactionCreate').default;
(async () => {
  const bot = new DiscordBot();
  await bot.registerCommands();
  assert.equal(registered.length, 35);
  assert.equal(new Set(registered.map(c => c.name)).size, 35);
  await bot.registerEvents();
  assert.ok(bot.listenerCount('interactionCreate') > 0);
  let executed = false;
  const command = { data: { toJSON: () => ({ default_member_permissions: '32' }) }, handler: async () => { executed = true; } };
  const client = { commands: new Map([['configurar', command]]), prisma: { guildConfig: { findUnique: async () => null } } };
  const interaction = { isChatInputCommand: () => true, inGuild: () => true, commandName: 'configurar', guildId: 'test', memberPermissions: { has: () => true }, reply: async () => {} };
  await event.execute(interaction, client);
  assert.equal(executed, true, 'Primeira configuração deve funcionar sem registro no banco');
  executed = false;
  interaction.memberPermissions.has = () => false;
  await event.execute(interaction, client);
  assert.equal(executed, false, 'Usuário sem permissão deve ser bloqueado');
  await bot.destroy();
  console.log('OK: 35 comandos, eventos, primeira configuração e autorização. Nenhuma chamada ao Discord.');
})().catch(error => { console.error(error); process.exitCode = 1; });
